"""Render nodes/<node>/<layer>/kustomization.yaml from features.toml and nodes/<node>/node.toml.

--check: render in memory and fail if anything is invalid or a committed file differs.
--base <git ref>: also fail if a provider component (CRDs, operators) disappears without teardown first.
"""
import pathlib, subprocess, sys, tomllib

LAYERS = ["infrastructure", "operators", "data", "apps"]
# Layers whose components own CRDs and finalizers. Flux prunes layers in no particular order, so these
# are removed only after the feature's objects are gone (teardown), never in the same change.
PROVIDERS = {"infrastructure", "operators"}
HEADER = "# Generated by `just features` from node.toml and features.toml. Do not edit.\n"

root = pathlib.Path(__file__).resolve().parent.parent
errors = []


def resolve(spec, items, where):
    """Features and components enabled by items (feature names or dep:<component>)."""
    features, components = spec["features"], spec["components"]
    enabled, deps = set(), set()

    def visit(item, stack):
        if item.startswith("dep:"):
            if item[4:] not in components:
                errors.append(f"{where}: unknown component {item[4:]!r}" + (f" (in feature {stack[-1]})" if stack else ""))
            deps.add(item[4:])
        elif item in stack:
            errors.append(f"{where}: feature cycle {' -> '.join(stack + (item,))}")
        elif item not in features:
            errors.append(f"{where}: unknown feature {item!r}" + (f" (in feature {stack[-1]})" if stack else ""))
        elif item not in enabled:
            enabled.add(item)
            for x in features[item]:
                visit(x, stack + (item,))

    for i in items:
        visit(i, ())
    return enabled, deps


def select(spec, node, where):
    """(enabled features, components on, provider components kept for teardown)."""
    enabled, on = resolve(spec, ["core", *node.get("features", [])], where)
    _, td = resolve(spec, node.get("teardown", []), f"{where} teardown")
    return enabled, on, {c for c in td - on if spec["components"].get(c) in PROVIDERS}


def render(spec, node_dir, node):
    where = node_dir.name
    enabled, on, kept = select(spec, node, where)
    if errors:
        return {}
    files = {}
    for layer in LAYERS:
        d = node_dir / layer
        resources, patches = [], []
        for c, l in spec["components"].items():
            if l != layer:
                continue
            version = d / f"{c}.version.yaml"
            if c not in on | kept:
                if version.exists():
                    errors.append(f"{where}: {version.relative_to(root)} is for disabled component {c}; delete it")
                continue
            resources.append(f"../../../components/{c}")
            if version.exists():
                patches.append(version.name)
            elif any("# per node" in p.read_text() for p in (root / "components" / c).glob("*.yaml")):
                errors.append(f"{where}: component {c} needs {version.relative_to(root)}")
        for path, c in spec.get("node-dirs", {}).items():
            if path.split("/")[0] == layer and (node_dir / path).is_dir():
                if c not in on:
                    errors.append(f"{where}: {path} needs component {c} (enable a feature with dep:{c})")
                resources.append(path.split("/", 1)[1])
        body = HEADER + "apiVersion: kustomize.config.k8s.io/v1beta1\nkind: Kustomization\n"
        body += "resources:" + ("".join(f"\n  - {r}" for r in resources) if resources else " []") + "\n"
        if patches:
            body += "patches:" + "".join(f"\n  - path: {p}" for p in patches) + "\n"
        files[d / "kustomization.yaml"] = body
    print(f"{where}: {', '.join(sorted(enabled))}" + (f" | teardown keeps: {', '.join(sorted(kept))}" if kept else ""))
    return files


def check_base(spec, nodes, ref):
    """Provider components switched off in one step (not via teardown) relative to ref."""
    def show(path):
        r = subprocess.run(["git", "-C", root, "show", f"{ref}:{path}"], capture_output=True, text=True)
        return tomllib.loads(r.stdout) if r.returncode == 0 else None

    base_spec = show("features.toml")
    if base_spec is None:
        return
    for node_dir, node in nodes.items():
        rel = node_dir.relative_to(root) / "node.toml"
        base_node = show(rel)
        if base_node is None:
            continue
        _, base_on, _ = select(base_spec, base_node, f"{ref}:{rel}")
        _, on, kept = select(spec, node, node_dir.name)
        for c in sorted(base_on - on - kept):
            if base_spec["components"].get(c) in PROVIDERS:
                errors.append(f"{node_dir.name}: provider {c} removed while its feature was on in {ref}; "
                              f"first move the feature to teardown in node.toml, merge, then remove it")


spec = tomllib.loads((root / "features.toml").read_text())
for c, layer in spec["components"].items():
    if layer not in LAYERS:
        errors.append(f"component {c}: unknown layer {layer!r}")
    if not (root / "components" / c / "kustomization.yaml").is_file():
        errors.append(f"component {c}: components/{c}/kustomization.yaml missing")

nodes = {p.parent: tomllib.loads(p.read_text()) for p in sorted((root / "nodes").glob("*/node.toml"))}
rendered = {}
for node_dir, node in nodes.items():
    rendered |= render(spec, node_dir, node)
if "--base" in sys.argv and not errors:
    check_base(spec, nodes, sys.argv[sys.argv.index("--base") + 1])
if errors:
    sys.exit("\n".join(f"error: {e}" for e in errors))

check = "--check" in sys.argv
stale = [p for p, body in rendered.items() if not p.exists() or p.read_text() != body]
for p in stale:
    if check:
        print(f"out of date: {p.relative_to(root)} (run: just features)")
    else:
        p.parent.mkdir(exist_ok=True)
        p.write_text(rendered[p])
        print(f"wrote {p.relative_to(root)}")
sys.exit(1 if check and stale else 0)
