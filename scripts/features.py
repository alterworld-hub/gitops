"""Render nodes/<node>/<layer>/kustomization.yaml from features.yaml and nodes/<node>/node.yaml.

--check: render in memory and fail if anything is invalid or a committed file differs.
YAML is read through $YQ (a yq command printing JSON; set by the justfile).
"""
import json, os, pathlib, shlex, subprocess, sys

PLATFORM_LAYERS = ["infrastructure", "operators"]
FEATURE_LAYERS = ["data", "apps"]
HEADER = "# Generated by `just features` from node.yaml and features.yaml. Do not edit.\n"

root = pathlib.Path(__file__).resolve().parent.parent
errors = []


def load(path):
    r = subprocess.run([*shlex.split(os.environ.get("YQ", "yq")), "-o=json", "."],
                       input=path.read_text(), capture_output=True, text=True)
    if r.returncode:
        sys.exit(f"error: {path.relative_to(root)}: {r.stderr.strip()}")
    return json.loads(r.stdout)


def resolve(catalog, items, where):
    """Features and components enabled by items (feature names or dep:<component>)."""
    features, components = catalog["features"], catalog["components"]
    enabled, deps = set(), set()

    def visit(item, stack):
        if item.startswith("dep:"):
            if item[4:] not in components:
                errors.append(f"{where}: unknown component {item[4:]!r}" + (f" (in feature {stack[-1]})" if stack else ""))
            deps.add(item[4:])
        elif item in stack:
            errors.append(f"{where}: feature cycle {' -> '.join(stack + (item,))}")
        elif item not in features:
            errors.append(f"{where}: unknown feature {item!r}" + (f" (in feature {stack[-1]})" if stack else ""))
        elif item not in enabled:
            enabled.add(item)
            for x in features[item]:
                visit(x, stack + (item,))

    for i in items:
        visit(i, ())
    return enabled, deps


def render(catalog, node_dir, node):
    where = node_dir.name
    enabled, deps = resolve(catalog, node.get("features", []), where)
    if errors:
        return {}
    layers = {layer: list(catalog["platform"].get(layer, [])) for layer in PLATFORM_LAYERS}
    layers |= {layer: [c for c, l in catalog["components"].items() if l == layer and c in deps] for layer in FEATURE_LAYERS}
    files = {}
    for layer, on in layers.items():
        d = node_dir / layer
        resources = [f"../../../components/{c}" for c in on]
        patches = []
        for c in on:
            version = d / f"{c}.version.yaml"
            if version.exists():
                patches.append(version.name)
            elif any("# per node" in p.read_text() for p in (root / "components" / c).glob("*.yaml")):
                errors.append(f"{where}: component {c} needs {version.relative_to(root)}")
        for version in sorted(d.glob("*.version.yaml")):
            if version.name.removesuffix(".version.yaml") not in on:
                errors.append(f"{where}: {version.relative_to(root)} is for a disabled component; delete it")
        for path, c in catalog.get("nodeDirs", {}).items():
            if path.split("/")[0] == layer and (node_dir / path).is_dir():
                if c not in on:
                    errors.append(f"{where}: {path} needs component {c} (enable a feature with dep:{c})")
                resources.append(path.split("/", 1)[1])
        body = HEADER + "apiVersion: kustomize.config.k8s.io/v1beta1\nkind: Kustomization\n"
        body += "resources:" + ("".join(f"\n  - {r}" for r in resources) if resources else " []") + "\n"
        if patches:
            body += "patches:" + "".join(f"\n  - path: {p}" for p in patches) + "\n"
        files[d / "kustomization.yaml"] = body
    print(f"{where}: {', '.join(sorted(enabled)) or '(platform only)'}")
    return files


catalog = load(root / "features.yaml")
platform = [c for layer in PLATFORM_LAYERS for c in catalog["platform"].get(layer, [])]
for layer in catalog["platform"]:
    if layer not in PLATFORM_LAYERS:
        errors.append(f"platform: layer {layer!r} is not one of {PLATFORM_LAYERS}")
for c, layer in catalog["components"].items():
    if layer not in FEATURE_LAYERS:
        errors.append(f"component {c}: layer {layer!r} is not one of {FEATURE_LAYERS} (providers belong to platform)")
    if c in platform:
        errors.append(f"component {c}: both platform and feature-toggled")
for c in [*platform, *catalog["components"]]:
    if not (root / "components" / c / "kustomization.yaml").is_file():
        errors.append(f"component {c}: components/{c}/kustomization.yaml missing")

rendered = {}
for p in sorted((root / "nodes").glob("*/node.yaml")):
    rendered |= render(catalog, p.parent, load(p))
if errors:
    sys.exit("\n".join(f"error: {e}" for e in errors))

check = "--check" in sys.argv
stale = [p for p, body in rendered.items() if not p.exists() or p.read_text() != body]
for p in stale:
    if check:
        print(f"out of date: {p.relative_to(root)} (run: just features)")
    else:
        p.parent.mkdir(exist_ok=True)
        p.write_text(rendered[p])
        print(f"wrote {p.relative_to(root)}")
sys.exit(1 if check and stale else 0)
