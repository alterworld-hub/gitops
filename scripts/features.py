"""Render nodes/<node>/<layer>/kustomization.yaml from features.toml and nodes/<node>/node.toml.

--check: render in memory and fail if anything is invalid or a committed file differs.
"""
import pathlib, sys, tomllib

LAYERS = ["infrastructure", "operators", "data", "apps"]
HEADER = "# Generated by `just features` from node.toml and features.toml. Do not edit.\n"

root = pathlib.Path(__file__).resolve().parent.parent
spec = tomllib.loads((root / "features.toml").read_text())
components, features, node_dirs = spec["components"], spec["features"], spec.get("node-dirs", {})
errors = []


def resolve(name, enabled, deps, stack=()):
    if name in stack:
        errors.append(f"feature cycle: {' -> '.join(stack + (name,))}")
        return
    if name not in features:
        errors.append(f"unknown feature {name!r}" + (f" (in {stack[-1]})" if stack else ""))
        return
    if name in enabled:
        return
    enabled.add(name)
    for item in features[name]:
        if item.startswith("dep:"):
            dep = item[4:]
            if dep not in components:
                errors.append(f"feature {name}: unknown component {dep!r}")
            deps.add(dep)
        else:
            resolve(item, enabled, deps, stack + (name,))


for c, layer in components.items():
    if layer not in LAYERS:
        errors.append(f"component {c}: unknown layer {layer!r}")
    if not (root / "components" / c / "kustomization.yaml").is_file():
        errors.append(f"component {c}: components/{c}/kustomization.yaml missing")


def render(node):
    enabled, deps = set(), set()
    for f in ["core", *tomllib.loads((node / "node.toml").read_text())["features"]]:
        resolve(f, enabled, deps)
    if errors:
        return {}
    files = {}
    for layer in LAYERS:
        d = node / layer
        resources, patches = [], []
        for c, l in components.items():
            per_node = any("# per node" in p.read_text() for p in (root / "components" / c).glob("*.yaml"))
            version = d / f"{c}.version.yaml"
            if l != layer:
                continue
            if c not in deps:
                if version.exists():
                    errors.append(f"{node.name}: {version.relative_to(root)} is for disabled component {c}; delete it")
                continue
            resources.append(f"../../../components/{c}")
            if version.exists():
                patches.append(version.name)
            elif per_node:
                errors.append(f"{node.name}: component {c} needs {version.relative_to(root)}")
        for path, c in node_dirs.items():
            if path.split("/")[0] == layer and (node / path).is_dir():
                if c not in deps:
                    errors.append(f"{node.name}: {path} needs component {c} (enable a feature with dep:{c})")
                resources.append(path.split("/", 1)[1])
        body = HEADER + "apiVersion: kustomize.config.k8s.io/v1beta1\nkind: Kustomization\n"
        body += "resources:" + ("".join(f"\n  - {r}" for r in resources) if resources else " []") + "\n"
        if patches:
            body += "patches:" + "".join(f"\n  - path: {p}" for p in patches) + "\n"
        files[d / "kustomization.yaml"] = body
    print(f"{node.name}: {', '.join(sorted(enabled))}")
    return files


rendered = {}
for node in sorted(p.parent for p in (root / "nodes").glob("*/node.toml")):
    rendered |= render(node)
if errors:
    sys.exit("\n".join(f"error: {e}" for e in errors))

check = "--check" in sys.argv
stale = [p for p, body in rendered.items() if not p.exists() or p.read_text() != body]
for p in stale:
    if check:
        print(f"out of date: {p.relative_to(root)} (run: just features)")
    else:
        p.parent.mkdir(exist_ok=True)
        p.write_text(rendered[p])
        print(f"wrote {p.relative_to(root)}")
sys.exit(1 if check and stale else 0)
